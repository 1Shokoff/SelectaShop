#!/bin/sh
# Права на единственный файл конфигурации.
#
# Файл читают ДВА разных пользователя, и это противоречие нужно разрешить
# явно:
#
#   * на хосте — тот, кто управляет проектом (обычно deploy);
#   * внутри контейнеров web и worker — пользователь приложения, uid 10001.
#
# Права 0600 закрывают файл от второго, и контейнер уходит в бесконечный
# перезапуск с кодом 78. Именно на этом всё и ломалось.
#
# Docker монтирует файл от имени своего демона, то есть от root, поэтому
# права каталога хоста контейнеру не помеха — значение имеют только права
# самого файла.
#
# Решение в два слоя:
#   1) каталог config/ закрывается правами 0750 — граница доступа на хосте;
#   2) файл отдаётся группе приложения с правами 0640.
#
# Если сменить группу нечем (нет root и нет sudo), файл получает 0644, а
# защиту обеспечивает только каталог. Это слабее, и скрипт об этом скажет.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
. "$ROOT/scripts/cert_lib.sh"

CONFIG="$ROOT/config/selectashop.toml"
CONFIG_DIR="$ROOT/config"

# Должно совпадать с APP_GID в docker/web/Dockerfile.
APP_GID=10001

if [ ! -f "$CONFIG" ]; then
    echo "  не найден $CONFIG — выполните: make init-config" >&2
    exit 78
fi

# Слой 1: каталог. Посторонний пользователь хоста не сможет даже войти.
chmod 0750 "$CONFIG_DIR" 2>/dev/null || run_as_root chmod 0750 "$CONFIG_DIR" || true

# Слой 2: сам файл.
if run_as_root chgrp "$APP_GID" "$CONFIG" && run_as_root chmod 0640 "$CONFIG"; then
    exit 0
fi

chmod 0644 "$CONFIG" 2>/dev/null || true
{
    echo
    echo "  ВНИМАНИЕ: не удалось сменить группу файла конфигурации"
    echo "  (нужны права root, а sudo недоступен)."
    echo
    echo "  Файлу выставлены права 0644, иначе контейнеры web и worker не"
    echo "  смогут его прочитать и уйдут в перезапуск с кодом 78."
    echo
    echo "  Секреты при этом закрыты каталогом config/ с правами 0750."
    echo "  Чтобы закрыть ещё и сам файл, выполните от root:"
    echo "      chgrp $APP_GID $CONFIG"
    echo "      chmod 0640 $CONFIG"
} >&2
